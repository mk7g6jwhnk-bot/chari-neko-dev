import assert from "node:assert/strict";
import {generateKeirinBranches} from "../keirin/sports/keirin-branches.mjs";
import {generateKeirinTerminals} from "../keirin/sports/keirin-terminals.mjs";

const scored=[
  rider(1,"A","自力",8.1),rider(2,"A","番手",7.4),rider(7,"A","三番手",6.8),
  rider(3,"B","自力",7.7),rider(4,"B","番手",8.8),
  rider(5,"C","自力",7.0),rider(6,"C","番手",7.6)
];
const lines=[
  line("A",[1,2,7]),line("B",[3,4]),line("C",[5,6])
];
const branches=generateKeirinBranches({scored,lines,lineConfidence:"高"});
const terminals=generateKeirinTerminals({scored,branches});

const banteB=branches.find(branch=>branch.id==="BANTE-B");
assert.ok(banteB,"B番手差し branch must exist");
assert.deepEqual(banteB.firstCandidates,["4"],"B番手差し first candidate must be B-line bante #4");

const banteBContributions=terminals.flatMap(terminal=>(terminal.branchContributions||[])
  .filter(c=>c.branchId==="BANTE-B")
  .map(c=>({order:terminal.order,contribution:c})));
assert.ok(banteBContributions.length>0,"B番手差し must create terminals");
assert.ok(banteBContributions.every(item=>item.order[0]===4),"Every B番手差し terminal must have #4 first");
assert.equal(banteBContributions.some(item=>item.order.join("-")==="3-4-6"),false,"3-4-6 must never be labeled/generated by B番手差し");

for(const branch of branches.filter(branch=>branch.branchType==="LEADER_HOLD"||branch.branchType==="MAKURI_SUCCESS")){
  const lineObj=lines.find(item=>item.id===branch.primaryLineId);
  assert.ok(lineObj);
  const expected=lineObj.leader.number;
  const contributions=terminals.flatMap(terminal=>(terminal.branchContributions||[])
    .filter(c=>c.branchId===branch.id)
    .map(c=>terminal.order));
  assert.ok(contributions.every(order=>order[0]===expected),`${branch.id} must keep its line leader first`);
}

console.log("Branch role semantic integrity tests passed.");

function rider(number,lineId,role,base){
  return {
    id:String(number),number,lineId,role,
    roleScores:{first:base,second:base-.2,third:base-.4},
    evidence:{recent:base,start:base-.1,sprint:base+.1,finish:base+.2,tracking:base+.15,stamina:5,lineTrust:5}
  };
}
function line(id,numbers){
  const members=numbers.map(number=>scored.find(item=>item.number===number));
  return {id,type:"ライン",members,leader:members.find(x=>x.role==="自力"),bante:members.find(x=>x.role==="番手"),third:members.find(x=>x.role==="三番手")||null};
}
