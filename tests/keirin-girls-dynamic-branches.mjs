import assert from "node:assert/strict";
import {generateKeirinBranches} from "../keirin/sports/keirin-branches.mjs";
const scored=[1,2,3,4,5,6,7].map((number,i)=>({id:String(number),number,role:"単騎",roleScores:{first:5+i*.2},evidence:{start:4+i*.5,sprint:5+(6-i)*.2,finish:5,tracking:5,recent:5,stamina:5}}));
const branches=generateKeirinBranches({scored,lines:[],lineConfidence:"高",raceCategory:"girls"});
assert.deepEqual(branches.map(branch=>branch.id),["BATTLE"],"official line evidenceがないガールズ戦で架空の先行・まくり枝を生成しない");
assert.equal(branches[0].label,"主導権争い・消耗");
assert.deepEqual(branches[0].firstCandidates,["1","2","3","4","5","6","7"]);
assert.equal(branches[0].primaryLineId,null);
assert.equal(branches[0].probability,1);
assert.equal(branches[0].priority,"hypothesis");
console.log("PASS girls evidence-safe hypothesis branching");
