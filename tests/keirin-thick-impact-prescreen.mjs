import assert from"node:assert/strict";
import{assessThickResearchCandidateImpact,assessThickResearchImpactBatch}from"../public/research-outcome-diagnostics.mjs";
const retained={ledgerId:"THICK-GLOBAL-001",candidateType:"THICK_HEAD_REPRESENTATION_REVIEW",status:"OOS_REPLICATED",decision:"RETAIN_RESEARCH_CANDIDATE"};
const baseline={mainHitRate:.28,supportHitRate:.17,returnRate:.94,betCount:10,thickShare:.20};
const safe={mainHitRate:.29,supportHitRate:.18,returnRate:.97,betCount:11,thickShare:.22};
const risky={mainHitRate:.23,supportHitRate:.16,returnRate:.88,betCount:14,thickShare:.30};
assert.equal(assessThickResearchCandidateImpact(retained,baseline,safe).status,"IMPACT_PRESCREEN_PASSED");
assert.equal(assessThickResearchCandidateImpact(retained,baseline,safe).decision,"ALLOW_SHADOW_PROPOSAL_ONLY");
const blocked=assessThickResearchCandidateImpact(retained,baseline,risky);
assert.equal(blocked.status,"SIDE_EFFECT_RISK_DETECTED");
assert.equal(blocked.decision,"BLOCK_RESEARCH_PROPOSAL");
assert.ok(blocked.counterEvidence.some(x=>x.type==="MAIN_HIT_RATE_REGRESSION"));
assert.ok(blocked.counterEvidence.some(x=>x.type==="RETURN_RATE_REGRESSION"));
assert.ok(blocked.counterEvidence.some(x=>x.type==="BET_COUNT_INFLATION"));
assert.equal(assessThickResearchCandidateImpact({...retained,status:"OOS_NOT_REPLICATED",decision:"REJECT_RESEARCH_CANDIDATE"},baseline,safe).status,"OOS_REPLICATION_REQUIRED");
assert.equal(assessThickResearchCandidateImpact(retained,{mainHitRate:.2},{mainHitRate:.21}).status,"IMPACT_EVIDENCE_INCOMPLETE");
const batch=assessThickResearchImpactBatch({evaluations:[retained]},{"THICK-GLOBAL-001":{baseline,proposal:safe}});
assert.equal(batch.status,"SHADOW_PROPOSALS_ELIGIBLE");
assert.equal(batch.productionWriteAllowed,false);
console.log("keirin thick impact prescreen tests: ok");
