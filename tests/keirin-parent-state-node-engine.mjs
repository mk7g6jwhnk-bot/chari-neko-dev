import assert from"node:assert/strict";
import{generateKeirinTerminals}from"../keirin/sports/keirin-terminals.mjs";
const r=(id,n,role,lineId)=>({id,number:n,role,lineId,roleScores:{first:7,second:7,third:7},evidence:{recent:7,start:7,sprint:7,finish:7,tracking:7,stamina:7,lineTrust:7}});
const scored=[r("1",1,"自力","A"),r("2",2,"番手","A"),r("3",3,"三番手","A"),r("4",4,"自力","B"),r("5",5,"番手","B")];
const branches=[{id:"LEAD-A",label:"A先行押し切り",scenario:"先行押し切り",branchType:"LEADER_HOLD",primaryLineId:"A",requiredFirstNumber:1,priority:"main",score:8,firstCandidates:["1"],firstCandidateScores:{"1":8}}];
const terminals=generateKeirinTerminals({scored,branches});
const t=terminals.find(x=>x.order.join("-")==="1-2-3")||terminals[0];
assert.ok(t);
assert.equal(t.nodeTrace.length,3);
const[a,b,c]=t.nodeTrace;
assert.equal(a.event.position,1);assert.equal(b.event.position,2);assert.equal(c.event.position,3);
assert.deepEqual(b.inheritedState,a.resultingState);
assert.deepEqual(c.inheritedState,b.resultingState);
assert.equal(b.resultingState.facts.winner,1);
assert.equal(c.resultingState.facts.winner,1);
assert.equal(c.resultingState.facts.second,Number(t.order[1]));
assert.ok(a.conditionalProbability>0&&b.conditionalProbability>0&&c.conditionalProbability>0);
assert.equal(terminals.generationAudit.nodeStateAudit.passed,true);
console.log("PASS parent-state inheritance + one-node-one-event");
