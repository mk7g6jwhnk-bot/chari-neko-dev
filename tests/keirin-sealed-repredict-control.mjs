import assert from "node:assert/strict";
import fs from "node:fs/promises";
const app=await fs.readFile(new URL("../public/app.mjs",import.meta.url),"utf8");
const openDetail=app.match(/function openDetail\(race\)\{[^\n]+/u)?.[0]||"";
const reloadBody=app.match(/async function reloadSavedPrediction[\s\S]+?(?=function openSealedSummary)/u)?.[0]||"";
assert.match(app,/openDetail\(race\).*selectedPredictionHash:predictionHash/s,"detail open must pin the immutable saved prediction identity");
assert.doesNotMatch(openDetail,/reuseSealedPrediction\(/,"opening detail must not eagerly read or regenerate the prediction");
assert.match(app,/metadata=1/,"saved display must perform lightweight canonical identity validation");
assert.match(app,/function handleDetailPrimary\(\).*state\.sealedLookupBusy/s,"normal action must not predict while seal lookup is pending");
assert.match(app,/RELOAD_SAVED\)\{void reloadSavedPrediction\(\{forceNetwork:true\}\)/s,"stale saved detail must expose a canonical-only reload path");
assert.match(app,/UPDATE_PREDICTION\)\{void predict\(\{refresh:true\}\)/s,"explicit secondary action remains the manual refresh path");
assert.doesNotMatch(reloadBody,/\bpredict\(/,"seal reload must not trigger prediction generation");
console.log("OK sealed prediction explicit repredict control test");
