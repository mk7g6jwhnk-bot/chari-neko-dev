import assert from "node:assert/strict";
import {createThickSealedValidationPackage,verifyThickSealedValidationPackage} from "../public/research-outcome-diagnostics.mjs";
const rp={status:"INDEPENDENT_REVIEW_PACKAGE_READY",reviewPackageId:"RP1",proposalId:"P1",proposalSeal:"PS1",scope:"THICK_ALLOCATION",change:{x:1},context:{venue:"A"},sourceChain:{oosVersion:"1"}};
const p={status:"PRIMARY_REVIEW_APPROVED",reviewerId:"A",primaryReviewSeal:"PRS1"};
const f={status:"DUAL_INDEPENDENT_REVIEW_APPROVED",decision:"ALLOW_SEALED_VALIDATION_ONLY",reviewerId:"B",primaryReviewSeal:"PRS1",finalReviewSeal:"FRS1"};
const pkg=createThickSealedValidationPackage(rp,p,f,{requiredMetrics:["returnRate","thickHitRate","mainHitRate"],validationCohort:{id:"cohort-1",frozen:true}});
assert.equal(pkg.status,"SEALED_VALIDATION_PACKAGE_READY");
assert.equal(pkg.decision,"RUN_SEALED_VALIDATION_ONLY");
assert.equal(pkg.safeguards.productionWriteAllowed,false);
const ok=verifyThickSealedValidationPackage(pkg);
assert.equal(ok.valid,true);
const bad={...pkg,requiredMetrics:[...pkg.requiredMetrics,"betCount"]};
const ng=verifyThickSealedValidationPackage(bad);
assert.equal(ng.status,"SEAL_MISMATCH");
console.log("keirin thick sealed validation package tests: ok");
const criteriaPkg=createThickSealedValidationPackage(rp,p,f,{requiredMetrics:["races","returnRate","thickHitRate","mainHitRate","supportHitRate","betCount"],validationCohort:{id:"cohort-criteria",frozen:true},validationCriteria:{minimumRaces:40,minimumReturnDelta:.01,minimumThickHitDelta:.02,maxMainHitDrop:.005,maxSupportHitDrop:.01,maxBetCountIncrease:.05}});
assert.equal(criteriaPkg.validationCriteria.minimumRaces,40);
assert.equal(criteriaPkg.validationCriteria.minimumReturnDelta,.01);
const criteriaTampered={...criteriaPkg,validationCriteria:{...criteriaPkg.validationCriteria,minimumRaces:30}};
assert.equal(verifyThickSealedValidationPackage(criteriaTampered).status,"SEAL_MISMATCH");
