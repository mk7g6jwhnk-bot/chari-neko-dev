import assert from 'node:assert/strict';
import fs from 'node:fs';
import { auditCoverConsistency } from '../research/cover-consistency-audit.mjs';
const read = name => JSON.parse(fs.readFileSync(new URL(`../research/${name}`, import.meta.url)));
const report = auditCoverConsistency(read('recommendation-thick-100r-source.json'), read('prediction-distance-100r-source.json'), read('prediction-distance-100r-evaluation.json'));
assert.equal(report.cohort.same, true);
assert.equal(report.cohort.temporalOrderSame, true);
assert.equal(report.cohort.raceCount, 100);
assert.equal(report.cohort.keyDifferences.length, 0);
assert.equal(report.cohort.resultAvailable, 100);
assert.equal(report.snapshot.same, true);
assert.equal(report.snapshot.predictionSealMismatches.length, 0);
assert.equal(report.snapshot.purchasePlanMismatches.length, 0);
assert.deepEqual(report.corrected.main, { tickets: 284, hits: 5 });
assert.deepEqual(report.corrected.cover, { tickets: 220, hits: 2 });
assert.deepEqual(report.corrected.thick, { tickets: 61, hits: 1 });
assert.deepEqual(report.corrected.total, { tickets: 504, hits: 7 });
assert.deepEqual(report.coverHits.map(row => row.raceKey), ['20260917-84-1', '20260917-63-2']);
assert.equal(report.coverHits.every(row => row.actualPurchased && row.cover && !row.main && !row.thick), true);
assert.deepEqual(report.mainHits.map(row => row.raceKey), ['20260912-53-12','20260917-84-6','20260917-73-6','20260917-13-6','20260917-83-1']);
assert.equal(report.integrity.predictionMismatch, 0);
assert.equal(report.integrity.purchaseMismatch, 0);
assert.equal(report.integrity.sealedResultMismatch, 0);
assert.equal(report.integrity.historicalMutation, 0);
assert.equal(report.integrity.productionChanged, false);
console.log('PASS same cohort, same sealed purchase plans, MAIN/COVER actual-vs-internal classification');
